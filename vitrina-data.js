window.AISH_LIKES = {
  LIKED: 'aish-liked',
  COUNTS: 'aish-like-counts',
  _map: function (key) { try { return JSON.parse(localStorage.getItem(key) || '{}'); } catch (e) { return {}; } },
  _save: function (key, obj) { try { localStorage.setItem(key, JSON.stringify(obj)); } catch (e) {} },
  hydrate: function (works) {
    var liked = this._map(this.LIKED), counts = this._map(this.COUNTS);
    (works || []).forEach(function (w) {
      if (counts[w.id] != null) w.likes = Number(counts[w.id]) || 0;
      w.liked = !!liked[w.id];
    });
    return works;
  },
  toggleLocal: function (w) {
    var liked = this._map(this.LIKED), counts = this._map(this.COUNTS);
    var on = !liked[w.id];
    if (on) liked[w.id] = 1; else delete liked[w.id];
    var n = Math.max(0, (Number(w.likes) || 0) + (on ? 1 : -1));
    counts[w.id] = n;
    w.liked = on; w.likes = n;
    this._save(this.LIKED, liked); this._save(this.COUNTS, counts);
    return { liked: on, likes: n };
  },
  isApiId: function (id) { return /^\d+$/.test(String(id == null ? '' : id)); }
};

