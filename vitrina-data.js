/* ---- Локализация демо-данных (опционально: данные остаются на RU, страницы берут переводы из /i18n/*.js) ----
   Ключи словаря: works.<id>.title, creators.<id>.name|about, networks.<id>.name|ph, demo.req.<id>.msg, vitrina.req.format.*.
   Если ключа нет (например, работа пользователя с числовым id) — возвращается исходное значение из данных. */
window.AISH_L = {
  _has: function (key) {
    var I = window.AISH_I18N; if (!I) return false;
    var d = I.LANG === 'en' ? window.AISH_DICT_EN : window.AISH_DICT_RU;
    return !!d && Object.prototype.hasOwnProperty.call(d, key);
  },
  tr: function (key, fallback, params) { return this._has(key) ? window.AISH_I18N.t(key, params) : fallback; },
  workTitle: function (w) { return w ? this.tr('works.' + w.id + '.title', w.title) : ''; },
  creatorName: function (c) { return c ? this.tr('creators.' + c.id + '.name', c.name) : ''; },
  creatorAbout: function (c) { return c ? this.tr('creators.' + c.id + '.about', c.about) : ''; },
  networkName: function (n) { return n ? this.tr('networks.' + n.id + '.name', n.name) : ''; },
  networkPh: function (n) { return n ? this.tr('networks.' + n.id + '.ph', n.ph || '', null) : ''; },
  reqMsg: function (r) { return r ? this.tr('demo.req.' + r.id + '.msg', r.msg) : ''; },
  /* fmt хранится как русская строка (канонический вид) — показываем по языку */
  fmtLabel: function (fmt) {
    var map = { 'Видео в максимальном качестве': 'video', 'Картинка PNG / 4K': 'image', 'Исходники и все дубли': 'source' };
    return map[fmt] ? this.tr('vitrina.req.format.' + map[fmt], fmt) : fmt;
  },
  /* «2 дня назад», «вчера», «черновик»… → локаль (в ru — как есть) */
  dateLabel: function (w) {
    var s = w && w.date; var I = window.AISH_I18N;
    if (!s || !I || I.LANG === 'ru') return s || '';
    if (/^черновик/i.test(s)) return I.t('works.date.draft');
    var n = null, unit = 'day';
    if (/^сегодня/i.test(s)) n = 0;
    else if (/^вчера/i.test(s)) n = -1;
    else if (/^неделю/i.test(s)) { n = -1; unit = 'week'; }
    else { var m = s.match(/^(\d+)\s*(дн|нед|час|мин)/i); if (m) { n = -Number(m[1]); unit = /^нед/i.test(m[2]) ? 'week' : /^час/i.test(m[2]) ? 'hour' : /^мин/i.test(m[2]) ? 'minute' : 'day'; } }
    if (n === null) return s;
    try { return new Intl.RelativeTimeFormat('en-US', { numeric: 'auto' }).format(n, unit); } catch (e) { return s; }
  }
};
