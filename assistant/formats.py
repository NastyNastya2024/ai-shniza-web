def _row(sub_id: str) -> tuple[str, str, str, str, str]:
    for row in SUBS:
        if row[0] == sub_id:
            return row
    raise KeyError(sub_id)


def categories(lang: str) -> list[dict]:
    en = lang == "en"
    return [{"id": i, "title": en_title if en else ru} for i, ru, en_title in CATS]


def subs_of(cat_id: str, lang: str) -> list[dict]:
    en = lang == "en"
    return [
        {"id": i, "title": en_title if en else ru, "kind": kind}
        for i, cat, ru, en_title, kind in SUBS if cat == cat_id
    ]


def title_of(sub_id: str, lang: str) -> str:
    _i, _c, ru, en, _k = _row(sub_id)
    return en if lang == "en" else ru


def kind_of(sub_id: str) -> str:
    return _row(sub_id)[4]


def cat_title(cat_id: str, lang: str) -> str:
    for i, ru, en in CATS:
        if i == cat_id:
            return en if lang == "en" else ru
    return cat_id


def match_sub(text: str) -> str | None:
    raw = text or ""
    for sub_id, rx in _SUB_RX:
        if rx.search(raw):
            return sub_id
    return None


def _idea(text: str) -> str:
    clean = " ".join((text or "").split())
    return clean[:500] if clean else "тема не указана — подставьте свой предмет"


def build(sub_id: str, idea: str) -> str:
    """Промпт с теми же разделами, что в примерах. Предмет — из запроса."""
    subject = _idea(idea)
    parts = _BODIES[sub_id](subject)
    return "\n\n".join(parts).strip()


def _b(subject: str, *blocks: str) -> list[str]:
    return [b.replace("{идея}", subject) for b in blocks]


